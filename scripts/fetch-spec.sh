#!/usr/bin/env bash
# Bring the harness specification's shared display data into the app, so the page's progress
# texts and tool-call display are the spec's own and cannot drift from it:
#
#   scripts/fetch-spec.sh <cli-ref>     (a tag such as v2.0.0-beta.9, or a branch)
#
# The specification lives in the LLeMbas CLI's repository (harness/), a git checkout beside this
# one by default (LEMBAS_CLI names another); the files are read from the ref, not from its
# working tree. Written:
#
#   ui/js/spec.js                          GENERATED: `progress` and `display` of harness/loop.json,
#                                          word for word, as the page's modules import them
#   tests/ui/conformance/progress.json     the spec's cases, which tests/ui holds the page to
#   tests/ui/conformance/display.json
#   tests/ui/conformance/SOURCE            the ref, the commit and the spec's version
#
# scripts/gen-i18n.py reads the sentences to translate out of ui/js/spec.js: run it afterwards.
# CI has no CLI checkout: the copies are committed.
set -euo pipefail
cd "$(dirname "$0")/.."

CLI="${LEMBAS_CLI:-../LLeMbas-CLI}"
OUT="tests/ui/conformance"

[ $# -eq 1 ] || { echo "usage: scripts/fetch-spec.sh <cli-ref>" >&2; exit 2; }
commit="$(git -C "$CLI" rev-parse --verify --quiet "$1^{commit}")" \
  || { echo "fetch-spec: $1 is not a commit in $CLI" >&2; exit 1; }
version="$(git -C "$CLI" show "$commit:harness/VERSION" | tr -d '[:space:]')"
mkdir -p "$OUT"
for f in progress.json display.json; do
  git -C "$CLI" show "$commit:harness/conformance/$f" > "$OUT/$f" \
    || { echo "fetch-spec: harness/conformance/$f is not at $1" >&2; exit 1; }
done
python3 - "$version" <(git -C "$CLI" show "$commit:harness/loop.json") > ui/js/spec.js <<'PY'
import json, sys
loop = json.load(open(sys.argv[2], encoding="utf-8"))
version = sys.argv[1]
missing = [k for k in ("progress", "display") if k not in loop]
if missing:
    sys.exit(f"fetch-spec: harness/loop.json has no {missing[0]} (spec {version})")
one = lambda v: json.dumps(v, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
print(f"""// The harness specification's shared display data (harness/loop.json of the LLeMbas CLI, spec
// {version}): `progress` -- the phases and their texts (progress.md) -- and `display` -- a tool
// call's title, states and facts, the end of a reply, the cards' actions (display.md).
// GENERATED by scripts/fetch-spec.sh, word for word; do not edit. One object a line:
// scripts/gen-i18n.py reads the sentences to translate from these two lines.

export const SPEC_VERSION = {json.dumps(version)}
export const PROGRESS = {one(loop["progress"])}
export const DISPLAY = {one(loop["display"])}""")
PY
printf 'LLeMbas CLI %s (%s) harness %s\n' "$1" "$commit" "$version" > "$OUT/SOURCE"
echo "fetch-spec: harness $version from LLeMbas CLI $1 (${commit:0:12}) -> ui/js/spec.js, $OUT"
