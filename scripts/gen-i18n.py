FIELD = re.compile(r"%\((\w+)\)s")
BRACES = re.compile(r"\{\{(\w+)\}\}")  # the spec's fields, which a translation must keep
SPEC = ROOT / "ui" / "js" / "spec.js"


def spec_sentences() -> tuple[str, ...]:
    """The harness spec's own sentences the page says (ui/js/spec.js, written by
    scripts/fetch-spec.sh from the CLI's harness/loop.json): the progress texts and the words
    their fields stand for, a call's facts, the cards' actions. Read from the file, so a
    sentence the spec gains or rewords is translated -- or reported -- without a list here."""
    data: dict[str, dict] = {}
    for line in SPEC.read_text(encoding="utf-8").splitlines():
        for name in ("PROGRESS", "DISPLAY"):
            head = f"export const {name} = "
            if line.startswith(head):
                data[name] = json.loads(line[len(head):])
    if set(data) != {"PROGRESS", "DISPLAY"}:
        sys.exit(f"gen-i18n: {SPEC} has no PROGRESS and DISPLAY line: run scripts/fetch-spec.sh")
    progress, display = data["PROGRESS"], data["DISPLAY"]
    out: list[str] = []
    for table in (progress["texts"], progress["reason"], progress["what"], progress["stopped_reason"]):
        out += list(table.values())
    out += [display["exit"], display["hits"], display["hit"]]
    for card in display["actions"].values():
        out += list(card.values())
    seen: list[str] = []
    for text in out:
        if text not in seen:
            seen.append(text)
    return tuple(seen)


def server_catalogue(server: Path, lang: str) -> dict[str, str]:
    """The server's MESSAGES for `lang`: the module loaded from its file, nothing imported."""
    path = server / "src" / "lembas" / "web" / "i18n" / f"{lang}.py"
    if not path.is_file():
        sys.exit(f"gen-i18n: {path} is missing: is {server} the LLeMbas server checkout?")
    spec = importlib.util.spec_from_file_location(f"lembas_i18n_{lang}", path)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    messages = getattr(module, "MESSAGES", None)
    if not isinstance(messages, dict):
        sys.exit(f"gen-i18n: {path} has no MESSAGES")
    NAMES[lang] = str(getattr(module, "NAME", "") or lang)
    return messages


NAMES: dict[str, str] = {}  # each language's own name for itself, as the server's catalogue says


def main() -> None:
    server = Path(sys.argv[1] if len(sys.argv) > 1 else os.environ.get("LEMBAS_SERVER", ROOT.parent / "LLeMbas"))
    catalogue: dict[str, dict[str, str]] = {}
    problems = 0
    # The page's own sentences, then the spec's (those not already among them).
    keys = KEYS + tuple(k for k in spec_sentences() if k not in KEYS)
    for lang in LANGS:
        theirs = server_catalogue(server, lang)
        ours = OWN.get(lang, {})
        table: dict[str, str] = {}
        from_server = 0
        for key in keys:
            text = theirs.get(key)
            if text:
                from_server += 1
            else:
                text = ours.get(key)
            if not text:
                print(f"gen-i18n: {lang}: no translation of {key!r} (English will show)", file=sys.stderr)
                problems += 1
                continue
            if set(FIELD.findall(text)) != set(FIELD.findall(key)) or set(BRACES.findall(text)) != set(BRACES.findall(key)):
                print(f"gen-i18n: {lang}: the fields of {text!r} do not match {key!r}", file=sys.stderr)
                problems += 1
                continue
            table[key] = text
        for key in ours:
            if key not in keys:
                print(f"gen-i18n: {lang}: OWN has {key!r}, which no page uses", file=sys.stderr)
                problems += 1
        catalogue[lang] = table
        print(f"gen-i18n: {lang}: {len(table)} sentences, {from_server} of the page's {len(keys)} from the server")

    body = json.dumps(catalogue, ensure_ascii=False, indent=2, sort_keys=True)
    names = json.dumps({"en": "English", **NAMES}, ensure_ascii=False, sort_keys=True)
    out = (
        "// The app's own pages' words in the server's languages. GENERATED by scripts/gen-i18n.py:\n"
        "// the sentences the server also has come from its web/i18n catalogues, the rest from the\n"
        "// script's own table. Do not edit; run the script.\n"
        "//\n"
        "// `t(text, fields)` is the page's English with `%(name)s` fields, as on the server; a\n"
        "// missing entry is the English. The language is the account's (kept from /me as\n"
        "// `lembas.account-language`) unless Settings chose this computer's or another\n"
        "// (`lembas.language`); the system's is navigator.language. English unless it is one of\n"
        "// these. Elements marked `data-i18n` (their text) and\n"
        "// `data-i18n-title`, `data-i18n-aria-label`, `data-i18n-placeholder` (that attribute)\n"
        "// are translated once the page is parsed; this script is deferred, before the page's.\n"
        '"use strict"\n'
        "\n"
        f"const LEMBAS_I18N = {body}\n"
        "\n"
        "// Each language's name for itself, for the choice in Settings.\n"
        f"const LEMBAS_LANGS = {names}\n"
        "\n"
        "// What the system's language gives, and what was chosen here instead (\"\" for the system's).\n"
        "const LEMBAS_SYSTEM_LANG = (() => {\n"
        '  const code = String(navigator.language || "").slice(0, 2).toLowerCase()\n'
        '  return Object.prototype.hasOwnProperty.call(LEMBAS_I18N, code) ? code : "en"\n'
        "})()\n"
        "// Settings' choice: \"\" for the account's language (as /me last said it), \"system\", or a code.\n"
        "const LEMBAS_CHOICE = (() => {\n"
        "  try {\n"
        '    return localStorage.getItem("lembas.language") || ""\n'
        "  } catch {\n"
        '    return ""\n'
        "  }\n"
        "})()\n"
        "const LEMBAS_CHOSEN_LANG = (() => {\n"
        "  const has = (code) => Object.prototype.hasOwnProperty.call(LEMBAS_LANGS, code)\n"
        '  if (LEMBAS_CHOICE === "system") return ""\n'
        "  if (has(LEMBAS_CHOICE)) return LEMBAS_CHOICE\n"
        '  let account = ""\n'
        "  try {\n"
        '    account = localStorage.getItem("lembas.account-language") || ""\n'
        "  } catch {}\n"
        '  return has(account) ? account : ""\n'
        "})()\n"
        "const LEMBAS_LANG = LEMBAS_CHOSEN_LANG || LEMBAS_SYSTEM_LANG\n"
        "document.documentElement.lang = LEMBAS_LANG\n"
        "\n"
        "function t(text, fields) {\n"
        '  const key = String(text).replace(/\\s+/g, " ").trim()\n'
        "  const table = LEMBAS_I18N[LEMBAS_LANG] || {}\n"
        "  const out = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : key\n"
        "  if (!fields) return out\n"
        "  return out.replace(/%\\((\\w+)\\)s/g, (all, name) =>\n"
        "    Object.prototype.hasOwnProperty.call(fields, name) ? String(fields[name]) : all)\n"
        "}\n"
        "\n"
        "function translatePage() {\n"
        '  for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = t(el.textContent)\n'
        '  for (const attr of ["title", "aria-label", "placeholder"]) {\n'
        "    for (const el of document.querySelectorAll(`[data-i18n-${attr}]`)) {\n"
        "      el.setAttribute(attr, t(el.getAttribute(attr)))\n"
        "    }\n"
        "  }\n"
        "}\n"
        'if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", translatePage)\n'
        "else translatePage()\n"
    )
    OUT.write_text(out, encoding="utf-8")
    print(f"gen-i18n: wrote {OUT.relative_to(ROOT)} ({len(LANGS)} languages, {len(keys)} sentences)")
    if problems:
        sys.exit(1)


if __name__ == "__main__":
    main()
